struct LocalAskPreparedData: Equatable {
    var memberID: UUID
    var records: [LocalAskPreparedRecord]
    var medications: [LocalAskMedicationSnapshot]
    var followUps: [LocalAskFollowUpSnapshot]
    var invertedIndex: LocalAskInvertedIndex

    init(
        memberID: UUID,
        records: [LocalAskPreparedRecord],
        medications: [LocalAskMedicationSnapshot],
        followUps: [LocalAskFollowUpSnapshot],
        invertedIndex: LocalAskInvertedIndex? = nil
    ) {
        self.memberID = memberID
        self.records = records
        self.medications = medications
        self.followUps = followUps
        self.invertedIndex = invertedIndex
            ?? LocalAskInvertedIndex(records: records)
    }
}
