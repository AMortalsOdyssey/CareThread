/// Runtime-only corpus assembled from the persisted per-record index shards.
/// Keeping postings out of SwiftData preserves cheap incremental shard updates,
/// while queries can obtain candidates and document frequencies without a
/// full-corpus scan.
struct LocalAskInvertedIndex: Equatable, Sendable {
    var postingsByTerm: [String: [LocalAskPosting]]
    var recordsByID: [UUID: LocalAskPreparedRecord]
    var documentTermCounts: [UUID: Int]

    init(records: [LocalAskPreparedRecord]) {
        var postings: [String: [LocalAskPosting]] = [:]
        var recordsByID: [UUID: LocalAskPreparedRecord] = [:]
        var documentTermCounts: [UUID: Int] = [:]
        recordsByID.reserveCapacity(records.count)
        documentTermCounts.reserveCapacity(records.count)

        for record in records {
            let recordID = record.snapshot.id
            recordsByID[recordID] = record
            documentTermCounts[recordID] = record.document.termCount
            for (term, frequency) in record.document.weightedTermFrequencies
            where frequency > 0 {
                postings[term, default: []].append(
                    LocalAskPosting(
                        recordID: recordID,
                        weightedFrequency: frequency
                    )
                )
            }
        }
        for term in Array(postings.keys) {
            postings[term]?.sort {
                $0.recordID.uuidString < $1.recordID.uuidString
            }
        }
        self.postingsByTerm = postings
        self.recordsByID = recordsByID
        self.documentTermCounts = documentTermCounts
    }

    func candidateRecordIDs(
        for terms: [String],
        allowedRecordIDs: Set<UUID>
    ) -> Set<UUID> {
        var candidates = Set<UUID>()
        for term in terms {
            for posting in postingsByTerm[term] ?? []
            where allowedRecordIDs.contains(posting.recordID) {
                candidates.insert(posting.recordID)
            }
        }
        return candidates
    }
}

