import Foundation

enum LocalAskIntent: String, Codable, CaseIterable, Hashable {
    case metric
    case medication
    case followUp
    case freeText
}

enum LocalAskTimeSelection: String, Codable, Equatable {
    case allTime
    case interval
    case mostRecent
    case earliest
}

struct LocalAskTimeScope: Equatable {
    var selection: LocalAskTimeSelection
    var interval: DateInterval?
    var displayLabel: String
    var didFallback: Bool

    static let allTime = LocalAskTimeScope(
        selection: .allTime,
        interval: nil,
        displayLabel: "全部时间",
        didFallback: false
    )

    func contains(_ date: Date) -> Bool {
        interval?.contains(date) ?? true
    }
}

