struct LocalAskResponse: Equatable {
    static let factualDisclaimer = "以下是从你的资料里找到的原始记录，CareThread 不做医学判断。"

    var intents: [LocalAskIntent]
    var timeScope: LocalAskTimeScope
    var metricFacts: [LocalAskMetricFact]
    var medicationFacts: [LocalAskMedicationFact]
    var followUpFacts: [LocalAskFollowUpFact]
    var hospitalFacts: [LocalAskHospitalFact]
    var recordHits: [LocalAskRecordHit]
    /// Reserved for a future on-device factual overview. Phase one leaves it nil.
    var factualOverview: String?

    var scopeNotice: String {
        if timeScope.didFallback {
            return "未识别到明确时间，已查找全部资料。"
        }
        return "查找范围：\(timeScope.displayLabel)"
    }

    var rankedSourceRecordIDs: [UUID] {
        var seen = Set<UUID>()
        let candidates = metricFacts.map(\.sourceRecordID)
            + medicationFacts.compactMap(\.sourceRecordID)
            + followUpFacts.compactMap(\.sourceRecordID)
            + hospitalFacts.map(\.sourceRecordID)
            + recordHits.map(\.recordID)
        return candidates.filter { seen.insert($0).inserted }
    }

    /// All text generated by CareThread itself. Source titles and source content
    /// are deliberately excluded because they remain verbatim local evidence.
    var generatedDisplayText: String {
        [Self.factualDisclaimer, scopeNotice, factualOverview]
            .compactMap { $0 }
            .joined(separator: "\n")
    }
}

