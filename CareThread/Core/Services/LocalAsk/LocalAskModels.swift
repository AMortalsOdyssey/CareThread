enum LocalAskSourceRoute: Equatable {
    case record(UUID)
    case medication(UUID)
    case followUp(UUID)

    static func medication(
        sourceRecordID: UUID?,
        medicationID: UUID,
        availableRecordIDs: Set<UUID>
    ) -> LocalAskSourceRoute {
        if let sourceRecordID,
           availableRecordIDs.contains(sourceRecordID) {
            return .record(sourceRecordID)
        }
        return .medication(medicationID)
    }

    static func followUp(
        sourceRecordID: UUID?,
        followUpID: UUID,
        availableRecordIDs: Set<UUID>
    ) -> LocalAskSourceRoute {
        if let sourceRecordID,
           availableRecordIDs.contains(sourceRecordID) {
            return .record(sourceRecordID)
        }
        return .followUp(followUpID)
    }
}

